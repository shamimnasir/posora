/** Roman numerals, up to the 999 the place-value builder can reach. */
const ROMAN: [number, string][] = [
  [1000, 'M'], [900, 'CM'], [500, 'D'], [400, 'CD'], [100, 'C'], [90, 'XC'],
  [50, 'L'], [40, 'XL'], [10, 'X'], [9, 'IX'], [5, 'V'], [4, 'IV'], [1, 'I'],
];
function roman(n: number): string {
  if (n <= 0) return 'কিছু নেই';
  let out = '', left = n;
  for (const [v, s] of ROMAN) while (left >= v) { out += s; left -= v; }
  return out;
}

/**
 * A number in Bangla words, up to 999.
 *
 * `numberWords` in `data/math.ts` already holds 0 to 100 one by one, because
 * Bangla number names below a hundred follow no rule worth writing; above it
 * they do, so the hundreds are assembled and the rest looked up.
 */
function words(n: number): string {
  if (n <= 100) return numberWords[n] ?? String(n);
  const h = Math.floor(n / 100), r = n % 100;
  const hs = `${numberWords[h]}শো`;
  return r === 0 ? hs : `${hs} ${numberWords[r]}`;
}

